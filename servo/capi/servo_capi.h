/* ---- Plain structs ---------------------------------------------------- */

typedef struct ServoRect {
    float x, y, width, height;         /* CSS px */
} ServoRect;

typedef struct ServoSize {
    uint32_t width, height;            /* device px */
} ServoSize;

typedef struct ServoProxyConfig {
    const char* http;      /* "host:port" or NULL */
    const char* https;
    const char* no_proxy;  /* comma-separated, may be NULL */
    const char* pac_url;   /* may be NULL; proxy auto-config */
} ServoProxyConfig;

/* ---- Rendering context ------------------------------------------------ */

/* Embedder-owned GL context (spec 5.2).  Servo never creates its own EGL
 * context when built this way; it paints into the framebuffer named by
 * framebuffer_object() on the thread where the context is current. */
typedef struct ServoRenderingContextVTable {
    void* user_data;
    bool     (*make_current)(void* ud);              /* no-op for Tuuli */
    void     (*swap_buffers)(void* ud);              /* no-op for Tuuli */
    void     (*size)(void* ud, ServoSize* out);      /* current FBO size */
    void     (*resize)(void* ud, ServoSize size);
    uint32_t (*framebuffer_object)(void* ud);        /* bound FBO id, 0 = default */
    void*    (*get_proc_address)(void* ud, const char* name);
    void     (*prepare_for_rendering)(void* ud);     /* called before paint */
    void     (*present)(void* ud);                   /* called after paint */
} ServoRenderingContextVTable;

ServoRenderingContext* servo_rendering_context_new_external(
    const ServoRenderingContextVTable* vtable, ServoGlApi api,
    uint32_t gl_major, uint32_t gl_minor);
void servo_rendering_context_free(ServoRenderingContext* ctx);

/* ---- Instance --------------------------------------------------------- */

typedef struct ServoInstanceCallbacks {
    void* user_data;
    /* May be called from any thread. Must only post to the embedder thread. */
    void (*wake_up)(void* ud);
    /* Servo hit an unrecoverable internal error.  Embedder thread. */
    void (*panic)(void* ud, const char* reason, const char* backtrace);
    /* Servo wants to open a new top-level webview (window.open, target=_blank).
     * Return a webview created with servo_webview_new_auxiliary(), or NULL. */
    ServoWebView* (*request_create_new_webview)(void* ud, ServoWebView* parent);
    /* System clipboard bridge (spec 8.3).  Synchronous, embedder thread.
     * The returned pointer stays valid until the next clipboard_get_text
     * call. */
    const char* (*clipboard_get_text)(void* ud);
    void (*clipboard_set_text)(void* ud, const char* text);
} ServoInstanceCallbacks;

typedef struct ServoInstanceConfig {
    const char* user_agent;              /* NULL = Servo default for platform */
    ServoUserAgentPlatform ua_platform;  /* engages is_mobile() (spec 5.4) */
    const char* certificate_path;        /* system CA bundle (spec 8.1) */
    const char* config_dir;              /* cookies, storage, cache root */
    const char* cache_dir;
    const ServoProxyConfig* proxy;       /* may be NULL */
    /* Servo preference overrides as "name=value" strings (see docs). */
    const char* const* prefs;
    size_t prefs_count;
    bool enable_hardware_video_decode;   /* gst-droid path (spec 8.2) */
    const char* gst_plugin_path;         /* extra GStreamer plugin dir or NULL */
    uint32_t layout_threads;             /* 0 = auto */
} ServoInstanceConfig;

/* Must be called with the rendering context current on the calling thread
 * (WebRender compiles its shader set here; spec 5.3). */
ServoInstance* servo_init(const ServoInstanceConfig* config,
                          ServoRenderingContext* ctx,
                          const ServoInstanceCallbacks* callbacks);

/* Runs pending Servo work; invokes callbacks.  Returns false once Servo has
 * shut down. */
bool servo_spin_event_loop(ServoInstance* servo);

/* Tears down Servo.  Rendering context must be current. */
void servo_deinit(ServoInstance* servo);

void servo_set_pref(ServoInstance* servo, const char* name, const char* value);
void servo_set_proxy(ServoInstance* servo, const ServoProxyConfig* proxy);

/* SiteDataManager (spec 7.3).  origin == NULL clears everything. */
void servo_clear_site_data(ServoInstance* servo, const char* origin,
                           uint32_t kinds /* ServoSiteDataKind bits */);

/* ---- WebView ---------------------------------------------------------- */

typedef struct ServoWebViewCallbacks {
    void* user_data;
    void (*url_changed)(void* ud, const char* url);
    void (*title_changed)(void* ud, const char* title);
    void (*load_status_changed)(void* ud, ServoLoadStatus status);
    /* RGBA8, row stride == width*4.  Pixels valid for the call only. */
    void (*favicon_changed)(void* ud, const uint8_t* rgba, uint32_t w, uint32_t h);
    void (*history_changed)(void* ud, const char* const* urls, size_t count,
                            size_t current);
    void (*new_frame_ready)(void* ud);
    void (*status_text_changed)(void* ud, const char* text);
    void (*cursor_changed)(void* ud, const char* css_cursor_name);
    void (*fullscreen_state_changed)(void* ud, bool fullscreen);
    /* Root scroll offset, pinch zoom and content size (CSS px): session
     * persistence and the pulley-menu handoff at content edges (spec 6.2). */
    void (*viewport_changed)(void* ud, float scroll_x, float scroll_y,
                             float pinch_zoom, float content_width,
                             float content_height);

    /* IME (spec 6.3). rect is the caret/element rect in CSS px. */
    void (*show_ime)(void* ud, ServoInputType type, const char* text,
                     bool multiline, ServoRect rect);
    void (*hide_ime)(void* ud);
    void (*ime_selection_changed)(void* ud, const char* text,
                                  uint32_t cursor, uint32_t anchor);

    /* Async requests.  The request object stays valid until the embedder
     * calls the matching servo_*_allow/deny/… function exactly once. */
    void (*request_permission)(void* ud, ServoPermissionRequest* req);
    void (*request_navigation)(void* ud, ServoNavigationRequest* req);
    void (*show_simple_dialog)(void* ud, ServoSimpleDialog* dialog);

    /* Hit-test result for servo_webview_request_context_menu(), or a
     * right-click / contextmenu event from content (spec 6.2). */
    void (*show_context_menu)(void* ud, float css_x, float css_y,
                              const char* link_url, const char* image_url,
                              const char* selected_text, bool editable);

    /* Downloads.  Servo performs the transfer; the embedder chooses the
     * destination with servo_download_accept(). */
    void (*download_requested)(void* ud, ServoDownload* download,
                               const char* url, const char* suggested_name,
                               const char* mime_type, int64_t total_bytes);
    void (*download_progress)(void* ud, ServoDownload* download,
                              int64_t received, int64_t total);
    void (*download_finished)(void* ud, ServoDownload* download, bool ok,
                              const char* error);

    void (*media_session_event)(void* ud, ServoMediaSessionEvent event,
                                const char* title, const char* artist,
                                const char* album, double position_s,
                                double duration_s);
    void (*notification_requested)(void* ud, const char* title,
                                   const char* body, const char* icon_url);
    void (*closed)(void* ud);
} ServoWebViewCallbacks;

