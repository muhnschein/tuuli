/*
 * servo_capi.h -- the C ABI of libservo as consumed by Tuuli.
 *
 * This header is Tuuli's *binding contract* with the pinned Servo release
 * (see ../SERVO_TAG).  It mirrors the `servo_capi` crate's exported surface
 * one-to-one and is the ONLY file in the repository that spells servo_*
 * symbols.  Everything above it goes through Tuuli::Engine (src/lib/engine).
 *
 * Rules:
 *  - The header in the libservo-devel RPM (generated by cbindgen from the
 *    pinned tag) is authoritative.  This copy exists so the shim can be
 *    compiled and type-checked on a host without Servo, against the
 *    no-op stub in stub/.  M0 exit criterion: the two headers diff clean
 *    modulo comments.  tools/check-capi-header.sh performs the comparison.
 *  - Anything Tuuli needs that is not here is added upstream in
 *    servo_capi, not by reaching into libservo from Rust glue (spec 3.3).
 *  - Threading (spec 4.2):
 *      * All servo_* calls except servo_webview_paint() and
 *        servo_deinit() are made from the thread that called servo_init()
 *        ("the embedder thread"; Tuuli's Qt GUI thread).
 *      * servo_webview_paint() is called from the thread on which the
 *        rendering context is current (Tuuli's Qt render thread).  The
 *        embedder guarantees no other servo_* call is in flight while it
 *        runs.
 *      * The wake_up callback may be invoked from ANY Servo thread and must
 *        do nothing but post a message to the embedder thread.
 *      * All other callbacks are invoked from inside
 *        servo_spin_event_loop() on the embedder thread.  Tuuli still
 *        marshals them through Qt::QueuedConnection before touching Qt
 *        objects (spec 4.2), so this is a guarantee we do not depend on.
 *  - Coordinates: input goes in as CSS pixels (spec 6.1).  Rects handed
 *    back by callbacks are CSS pixels relative to the webview origin.
 *  - Strings are UTF-8, NUL-terminated, and owned by the callee for the
 *    duration of the call only.  Strings returned by servo_* getters are
 *    freed with servo_string_free().
 */

